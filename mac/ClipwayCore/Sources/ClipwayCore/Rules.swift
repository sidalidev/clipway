import Foundation

/// Freshness, duplicates and own items (docs/PROTOCOL.md, section 3.4).
public struct ReceiveGuard: Codable, Equatable, Sendable {
    public static let maxAgeMs: Int64 = (24 * 60 + 10) * 60_000
    public static let maxFutureMs: Int64 = 10 * 60_000
    public static let rememberMs: Int64 = 48 * 3_600_000
    public static let rememberMax = 2_000

    public enum Verdict: Equatable, Sendable {
        case accept
        /// Sent by this device: dropped without an ack.
        case own
        case stale
        case future
        case duplicate

        /// Every dropped item is acknowledged, except our own.
        public var acknowledge: Bool { self != .own }
    }

    /// Item id to the time it was seen (ms).
    public private(set) var seen: [String: Int64] = [:]

    public init() {}

    public func check(_ head: Head, ownDevice: String, now: Int64) -> Verdict {
        if head.device.id == ownDevice { return .own }
        if head.ts < now - Self.maxAgeMs { return .stale }
        if head.ts > now + Self.maxFutureMs { return .future }
        // An offer is only valid 2 minutes: its sender has stopped listening (section 14.3).
        if head.type == .offer && head.ts < now - Head.offerMs { return .stale }
        if let at = seen[head.item], at >= now - Self.rememberMs { return .duplicate }
        return .accept
    }

    public mutating func remember(_ item: String, now: Int64) {
        seen[item] = now
        let limit = now - Self.rememberMs
        seen = seen.filter { $0.value >= limit }
        if seen.count > Self.rememberMax {
            let keep = seen.sorted { $0.value > $1.value }.prefix(Self.rememberMax)
            seen = Dictionary(uniqueKeysWithValues: keep.map { ($0.key, $0.value) })
        }
    }
}

/// Which received text or image may replace the clipboard (section 3.5): the newest by ts,
/// and only if it is less than 10 minutes old. The rest goes to history only.
public struct ClipboardRecency: Codable, Equatable, Sendable {
    public static let maxAgeMs: Int64 = 10 * 60_000
    public private(set) var newest: Int64 = 0

    public init() {}

    public mutating func shouldWrite(ts: Int64, now: Int64) -> Bool {
        guard now - ts < Self.maxAgeMs, ts >= newest else { return false }
        newest = ts
        return true
    }
}

/// Echo guard (section 5.5): skip sending content whose fp was received or sent less than 10 s ago.
public struct EchoGuard: Sendable {
    public static let windowMs: Int64 = 10_000
    private var last: (fp: String, at: Int64)?

    public init() {}

    public mutating func note(_ fp: String, now: Int64) { last = (fp, now) }

    public func isEcho(_ fp: String, now: Int64) -> Bool {
        guard let last else { return false }
        return last.fp == fp && now - last.at < Self.windowMs
    }
}

/// What the clipboard watch does with a pasteboard change (sections 5.4 and 7).
public enum PasteboardRule {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Marks who wrote the pasteboard; Clipway marks its own writes with its bundle id.
    public static let source = "org.nspasteboard.source"
    public static let fileURL = "public.file-url"
    public static let text = "public.utf8-plain-text"
    public static let png = "public.png"
    public static let tiff = "public.tiff"

    public enum Decision: Equatable, Sendable {
        case text
        case image(type: String)
        /// Marked by a password manager or as auto-generated: never sent.
        case secret
        /// A Finder copy: sent with Send a file only.
        case files
        /// Images are off, or nothing Clipway sends.
        case nothing
    }

    /// types: the types of each pasteboard item of the change.
    public static func decide(_ types: [[String]], imagesToo: Bool) -> Decision {
        let all = Set(types.flatMap { $0 })
        if all.contains(concealed) || all.contains(transient) || all.contains(autoGenerated) { return .secret }
        if all.contains(fileURL) { return .files }
        guard let first = types.first else { return .nothing }
        if first.contains(text) { return .text }
        guard imagesToo else { return .nothing }
        if first.contains(png) { return .image(type: png) }
        if first.contains(tiff) { return .image(type: tiff) }
        return .nothing
    }
}
