import CryptoKit
import Foundation
import XCTest
@testable import ClipwayCore

/// Receive rules, pasteboard filtering, file names, relay addresses, history and its export.
final class RulesTests: XCTestCase {
    typealias C = ClipwayCrypto
    let me = C.randomId()
    let now: Int64 = 1_792_300_000_000

    func head(device: String = "0f1e2d3c4b5a69788796a5b4c3d2e1f0", ts: Int64, item: String = C.randomId()) -> Head {
        Head(type: .text, item: item, device: Device(id: device, name: "Pixel", kind: .android), ts: ts)
    }

    func testFreshnessDuplicatesAndOwnItems() {
        var g = ReceiveGuard()
        XCTAssertEqual(g.check(head(ts: now), ownDevice: me, now: now), .accept)
        XCTAssertEqual(g.check(head(device: me, ts: now), ownDevice: me, now: now), .own)
        XCTAssertFalse(ReceiveGuard.Verdict.own.acknowledge)
        XCTAssertEqual(g.check(head(ts: now - ReceiveGuard.maxAgeMs - 1), ownDevice: me, now: now), .stale)
        XCTAssertEqual(g.check(head(ts: now - ReceiveGuard.maxAgeMs + 1), ownDevice: me, now: now), .accept)
        XCTAssertEqual(g.check(head(ts: now + 10 * 60_000 + 1), ownDevice: me, now: now), .future)
        XCTAssertTrue(ReceiveGuard.Verdict.stale.acknowledge)

        let h = head(ts: now)
        g.remember(h.item, now: now)
        XCTAssertEqual(g.check(h, ownDevice: me, now: now + 1000), .duplicate)
        XCTAssertEqual(g.check(h, ownDevice: me, now: now + ReceiveGuard.rememberMs + 1), .stale)

        for i in 0..<2_100 { g.remember(C.randomId(), now: now + Int64(i)) }
        XCTAssertEqual(g.seen.count, ReceiveGuard.rememberMax)
    }

    func testOnlyTheNewestRecentItemReachesTheClipboard() {
        var r = ClipboardRecency()
        XCTAssertTrue(r.shouldWrite(ts: now - 1000, now: now))
        XCTAssertFalse(r.shouldWrite(ts: now - 2000, now: now), "older than the last one written")
        XCTAssertTrue(r.shouldWrite(ts: now, now: now))
        var fresh = ClipboardRecency()
        XCTAssertFalse(fresh.shouldWrite(ts: now - 10 * 60_000, now: now), "10 minutes old goes to history only")
    }

    func testEchoGuard() {
        var e = EchoGuard()
        XCTAssertFalse(e.isEcho("aa", now: now))
        e.note("aa", now: now)
        XCTAssertTrue(e.isEcho("aa", now: now + 9_999))
        XCTAssertFalse(e.isEcho("aa", now: now + 10_000))
        XCTAssertFalse(e.isEcho("bb", now: now + 1))
    }

    /// What password managers set is never sent; Finder copies are not sent automatically.
    func testPasteboardFiltering() {
        typealias P = PasteboardRule
        XCTAssertEqual(P.decide([[P.text]], imagesToo: true), .text)
        XCTAssertEqual(P.decide([[P.text, P.concealed]], imagesToo: true), .secret)
        XCTAssertEqual(P.decide([[P.text], [P.transient]], imagesToo: true), .secret)
        XCTAssertEqual(P.decide([[P.text, P.autoGenerated]], imagesToo: true), .secret)
        XCTAssertEqual(P.decide([[P.fileURL, P.text, P.tiff]], imagesToo: true), .files)
        XCTAssertEqual(P.decide([[P.tiff, P.png]], imagesToo: true), .image(type: P.png))
        XCTAssertEqual(P.decide([[P.tiff]], imagesToo: true), .image(type: P.tiff))
        XCTAssertEqual(P.decide([[P.tiff]], imagesToo: false), .nothing)
        XCTAssertEqual(P.decide([["public.rtf", P.text]], imagesToo: false), .text)
        XCTAssertEqual(P.decide([], imagesToo: true), .nothing)
        XCTAssertEqual(P.decide([["com.apple.pasteboard.promised-file-url"]], imagesToo: true), .nothing)
    }

    func testFileNamesAreSanitized() {
        XCTAssertEqual(FileNames.sanitize("report.pdf"), "report.pdf")
        XCTAssertEqual(FileNames.sanitize("../../etc/passwd"), "etcpasswd")
        XCTAssertEqual(FileNames.sanitize("..\\..\\boot.ini"), "boot.ini")
        XCTAssertEqual(FileNames.sanitize(".hidden"), "hidden")
        XCTAssertEqual(FileNames.sanitize("a\u{0}b\u{7}c\nd.txt"), "abcd.txt")
        XCTAssertEqual(FileNames.sanitize("invoice\u{202E}fdp.app"), "invoicefdp.app")
        XCTAssertEqual(FileNames.sanitize("Résumé café ☕.txt"), "Résumé café ☕.txt")
        XCTAssertEqual(FileNames.sanitize("..."), "file")
        XCTAssertEqual(FileNames.sanitize("   "), "file")
        let long = String(repeating: "a", count: 300) + ".jpeg"
        let cut = FileNames.sanitize(long)
        XCTAssertEqual(cut.count, 120)
        XCTAssertTrue(cut.hasSuffix(".jpeg"))

        var taken: Set<String> = ["photo.jpg", "photo 2.jpg", "notes"]
        XCTAssertEqual(FileNames.unique("photo.jpg") { taken.contains($0) }, "photo 3.jpg")
        XCTAssertEqual(FileNames.unique("notes") { taken.contains($0) }, "notes 2")
        taken = []
        XCTAssertEqual(FileNames.unique("new.png") { taken.contains($0) }, "new.png")
    }

    func testRelayAddresses() throws {
        XCTAssertEqual(try RelayAddress.normalize(" https://clip.sidali.dev/ ", allowLocalHTTP: false), "https://clip.sidali.dev")
        XCTAssertEqual(RelayAddress.webSocketURL("https://clip.sidali.dev")?.absoluteString, "wss://clip.sidali.dev/ws")
        XCTAssertEqual(RelayAddress.webSocketURL("https://example.org/clipway")?.absoluteString, "wss://example.org/clipway/ws")
        XCTAssertEqual(RelayAddress.webSocketURL("http://127.0.0.1:7710")?.absoluteString, "ws://127.0.0.1:7710/ws")
        XCTAssertEqual(try RelayAddress.normalize("http://127.0.0.1:7710", allowLocalHTTP: true), "http://127.0.0.1:7710")
        XCTAssertThrowsError(try RelayAddress.normalize("http://127.0.0.1:7710", allowLocalHTTP: false))
        XCTAssertThrowsError(try RelayAddress.normalize("http://example.org", allowLocalHTTP: true))
        XCTAssertThrowsError(try RelayAddress.normalize("ftp://example.org", allowLocalHTTP: true))
        XCTAssertThrowsError(try RelayAddress.normalize("clip.sidali.dev", allowLocalHTTP: true))
        XCTAssertEqual(try RelayAddress.normalize("Https://Clip.Sidali.dev/", allowLocalHTTP: false), "https://clip.sidali.dev")
        XCTAssertEqual(try RelayAddress.normalize("HTTPS://example.org/Clipway", allowLocalHTTP: false), "https://example.org/Clipway")
        XCTAssertEqual(try RelayAddress.normalize("Http://LocalHost:7710", allowLocalHTTP: true), "http://localhost:7710")
        XCTAssertThrowsError(try RelayAddress.normalize("https://example.org/?id=1", allowLocalHTTP: true))
        XCTAssertTrue(Version.isLower("0.1.0", than: "0.2.0"))
        XCTAssertTrue(Version.isLower("0.9.9", than: "0.10.0"))
        XCTAssertFalse(Version.isLower("1.0.0", than: "1.0.0"))
    }

    func testDeviceNames() {
        XCTAssertEqual(Device.cleanName("  ", fallback: "Mac"), "Mac")
        XCTAssertEqual(Device.cleanName(String(repeating: "é", count: 80), fallback: "Mac").unicodeScalars.count, 64)
        XCTAssertEqual(Device.cleanName("Sid's\nMac", fallback: "Mac"), "Sid'sMac")
    }

    func testSecurityReviewDateMatchesTheNewestReview() throws {
        let docs = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("docs/security")
        let reviews = try FileManager.default.contentsOfDirectory(atPath: docs.path)
            .filter { $0.range(of: #"^\d{4}-\d{2}-\d{2}\.md$"#, options: .regularExpression) != nil }.sorted()
        XCTAssertEqual(ClipwayInfo.lastSecurityReview + ".md", reviews.last)
    }

    // MARK: History

    func makeStore(byteLimit: Int = HistoryStore.maxBytes) throws -> (HistoryStore, URL, SymmetricKey) {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("clipway-test-" + C.randomId())
        let key = SymmetricKey(size: .bits256)
        addTeardownBlock { try? FileManager.default.removeItem(at: dir) }
        return (HistoryStore(directory: dir, key: key, byteLimit: byteLimit), dir, key)
    }

    func entry(_ i: Int, type: ItemType = .text, text: String? = "hello", size: Int = 5) -> HistoryEntry {
        HistoryEntry(id: C.randomId(), type: type, direction: .received, device: "Pixel", kind: .android, ts: now + Int64(i),
                     mime: type == .text ? "text/plain" : "image/png", size: size, fp: C.randomId(), text: type == .text ? text : nil)
    }

    func testHistoryIsEncryptedAndLimited() throws {
        let (store, dir, key) = try makeStore()
        try store.add(entry(0, text: "secret clipboard words"))
        let png = Data(base64Encoded: "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8//8/AwAFAAH/Wk6G4QAAAABJRU5ErkJggg==")!
        let image = entry(1, type: .image, size: png.count)
        try store.add(image, image: png)

        let raw = try Data(contentsOf: dir.appendingPathComponent("history.bin"))
        XCTAssertNil(raw.range(of: Data("secret clipboard".utf8)), "history.bin is encrypted")
        let rawImage = try Data(contentsOf: dir.appendingPathComponent("items/\(image.id).bin"))
        XCTAssertNil(rawImage.range(of: png.prefix(8)))

        let again = HistoryStore(directory: dir, key: key)
        XCTAssertEqual(again.load().map(\.id), [image.id, store.entries[1].id])
        XCTAssertEqual(again.image(image.id), png)

        let wrongKey = HistoryStore(directory: dir, key: SymmetricKey(size: .bits256))
        XCTAssertEqual(wrongKey.load(), [], "without the key, nothing is readable")
        XCTAssertFalse(FileManager.default.fileExists(atPath: dir.appendingPathComponent("items").path),
                       "unreadable images are removed with the unreadable index")

        let (big, _, _) = try makeStore()
        for i in 0..<60 { try big.add(entry(i)) }
        XCTAssertEqual(big.entries.count, HistoryStore.maxItems)
        XCTAssertEqual(big.entries.first?.ts, now + 59)

        let limit = 3 * 1_048_576
        let (full, _, _) = try makeStore(byteLimit: limit)
        let mb = String(repeating: "x", count: 1_048_000)
        for i in 0..<5 { try full.add(entry(i, text: mb + "\(i)", size: mb.utf8.count)) }
        XCTAssertEqual(full.entries.count, 5)
        XCTAssertTrue(full.entries.reduce(0) { $0 + $1.contentBytes } <= limit)
        XCTAssertTrue(full.entries.last!.contentRemoved)
        XCTAssertFalse(full.entries.first!.contentRemoved)
    }

    func testRemoveClearAndUndo() throws {
        let (store, _, _) = try makeStore()
        let a = entry(0), b = entry(1)
        try store.add(a)
        try store.add(b)
        let removed = store.remove(a.id)!
        XCTAssertEqual(store.entries.map(\.id), [b.id])
        store.restore([removed])
        XCTAssertEqual(store.entries.map(\.id), [b.id, a.id])
        let all = store.clear()
        XCTAssertTrue(store.entries.isEmpty)
        store.restore(all)
        XCTAssertEqual(store.entries.count, 2)
    }

    /// The export opens without Clipway: checked with unzip and the JSON parser.
    func testExportIsAPlainZip() throws {
        let (store, dir, _) = try makeStore()
        try store.add(entry(0, text: "café ☕"))
        let png = Data(base64Encoded: "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8//8/AwAFAAH/Wk6G4QAAAABJRU5ErkJggg==")!
        let image = entry(1, type: .image, size: png.count)
        try store.add(image, image: png)
        let zip = try store.exportZip()
        let file = dir.appendingPathComponent("export.zip")
        try zip.write(to: file)

        let out = dir.appendingPathComponent("unzipped")
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/unzip")
        p.arguments = ["-q", file.path, "-d", out.path]
        try p.run()
        p.waitUntilExit()
        XCTAssertEqual(p.terminationStatus, 0)
        let json = try JSONSerialization.jsonObject(with: Data(contentsOf: out.appendingPathComponent("history.json"))) as! [[String: Any]]
        XCTAssertEqual(json.count, 2)
        XCTAssertEqual(json[1]["text"] as? String, "café ☕")
        XCTAssertEqual(json[0]["image"] as? String, "items/\(image.id).png")
        XCTAssertEqual(try Data(contentsOf: out.appendingPathComponent("items/\(image.id).png")), png)
        XCTAssertEqual(CRC32.checksum(Data("123456789".utf8)), 0xCBF4_3926)
    }
}
